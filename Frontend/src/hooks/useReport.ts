import { useState } from 'react';
import { apiClient } from '@/api/client';
import { ENDPOINTS } from '@/api/endpoints';
import { RouteCandidate, PlanResponse } from '@/types';

export function useReport() {
  const [isDownloading, setIsDownloading] = useState(false);
  const [downloadError, setDownloadError] = useState<string | null>(null);
  const [downloadSuccess, setDownloadSuccess] = useState(false);

  const downloadReport = async (
    tripId: string,
    planData?: PlanResponse | null,
    selectedRoute?: RouteCandidate
  ) => {
    setIsDownloading(true);
    setDownloadError(null);
    setDownloadSuccess(false);

    const isMock = import.meta.env.VITE_USE_MOCK_DATA === 'true';

    try {
      if (!isMock) {
        const blob = await apiClient<Blob>(ENDPOINTS.REPORT(tripId), {
          headers: {
            Accept: 'application/pdf',
          },
        });
        const url = window.URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `GreenRoute_AI_Carbon_Report_${tripId}.pdf`;
        document.body.appendChild(a);
        a.click();
        window.URL.revokeObjectURL(url);
        document.body.removeChild(a);
        setDownloadSuccess(true);
      } else {
        // Demonstration Mode PDF / Document Generator
        await new Promise((res) => setTimeout(res, 1200));

        const route = selectedRoute || planData?.routes[0];
        const textContent = `
================================================================================
                    GREENROUTE AI – CARBON & LOGISTICS AUDIT
                 [DEMONSTRATION REPORT - NOT AN OFFICIAL AUDIT]
================================================================================

Trip Reference ID   : ${tripId}
Generated At        : ${new Date().toISOString()}
Origin Hub          : ${planData?.origin.name || 'Pune Industrial Zone'}
Destination Port    : ${planData?.destination.name || 'JNPT Navi Mumbai'}
Allocated Vehicle   : ${planData?.vehicle.name || 'Heavy Commercial Vehicle'}
Payload Weight      : ${planData?.cargo_load_tons || 18.5} Metric Tonnes

--------------------------------------------------------------------------------
1. SELECTED ROUTE AUDIT
--------------------------------------------------------------------------------
Route Profile       : ${route?.name || 'Yashwantrao Chavan Expressway'}
Total Distance      : ${route?.distance_km || 142.5} km
Estimated Transit   : ${route?.duration_hours || 2.85} hours
Fuel Consumption    : ${route?.fuel_liters || 44.8} Liters (Uncertainty: ±${route?.fuel_uncertainty_pct || 3.8}%)
Calculated CO2      : ${route?.co2_kg || 118.2} kg CO2e
Financial Estimate  : INR ${route?.cost_inr || 5840} (Tolls: INR ${route?.toll_charges_inr || 620})
Climate Risk Score  : ${route?.risk_score || 0.18} (Scale: 0-1)

--------------------------------------------------------------------------------
2. MULTI-OBJECTIVE TRADE-OFFS & OPTIMIZATION NARRATIVE
--------------------------------------------------------------------------------
${planData?.explainability.recommendation_narrative || 'Optimized for minimum carbon emission and low climate risk along the Western Ghats corridor.'}

Key Trade-Off Notes:
${planData?.explainability.trade_offs.map((t) => ` • ${t}`).join('\n') || ' • Standard baseline trajectory'}

--------------------------------------------------------------------------------
3. COUNTERFACTUAL EMISSIONS REDUCTION
--------------------------------------------------------------------------------
Scenario: ${planData?.explainability.counterfactual.description || 'Payload optimization'}
Potential Fuel Saved: ${planData?.explainability.counterfactual.fuel_saved_liters || 5.8} Liters
Potential CO2 Cut   : ${planData?.explainability.counterfactual.co2_reduced_kg || 15.3} kg CO2e

--------------------------------------------------------------------------------
4. DATA SOURCE LIMITATIONS & METHODOLOGY
--------------------------------------------------------------------------------
- Routing Topology  : OpenFreeMap Vector Street Routing
- Gradient Profile  : SRTM 30m Digital Elevation Model
- Emissions Factor  : 2.68 kg CO2/L High-Speed Diesel (IPCC Tier 2 Framework)
- Audit Mode        : Demonstration / Mock Pipeline (VITE_USE_MOCK_DATA=true)

================================================================================
Generated by GreenRoute AI Intelligence Platform | Designed for Competition Evaluation
================================================================================
        `.trim();

        const blob = new Blob([textContent], { type: 'text/plain;charset=utf-8' });
        const url = window.URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `GreenRoute_Demo_Carbon_Audit_${tripId}.txt`;
        document.body.appendChild(a);
        a.click();
        window.URL.revokeObjectURL(url);
        document.body.removeChild(a);
        setDownloadSuccess(true);
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Failed to download report.';
      setDownloadError(msg);
    } finally {
      setIsDownloading(false);
    }
  };

  return {
    downloadReport,
    isDownloading,
    downloadError,
    downloadSuccess,
    resetStatus: () => {
      setDownloadError(null);
      setDownloadSuccess(false);
    },
  };
}

